#!/usr/bin/env bash
# Laptop-side setup for the BrowserMCP SSH tunnel to the S5.
# Writes a tunnel wrapper + a systemd user service (both via quoted heredocs,
# so every $ passes through literally), enables the service, and verifies the
# daemon answers through the tunnel. Run ONCE on the laptop that runs Chrome
# (NOT on the S5):
#   scp ari@100.85.113.67:/home/ari/remote-server/scripts/setup-browsermcp-tunnel.sh /tmp/ \
#     && bash /tmp/setup-browsermcp-tunnel.sh
# Idempotent — safe to re-run. OFFLINE=1 writes files only (used by tests).
set -euo pipefail

S5_SSH_TARGET="${S5_SSH_TARGET:-ari@100.85.113.67}"
BIN_DIR="${TARGET_HOME:-${HOME}}/.local/bin"
UNIT_DIR="${TARGET_HOME:-${HOME}}/.config/systemd/user"
WRAPPER="${BIN_DIR}/browsermcp-tunnel.sh"
UNIT="${UNIT_DIR}/browsermcp-tunnel.service"
OFFLINE="${OFFLINE:-0}"

mkdir -p "${BIN_DIR}" "${UNIT_DIR}"

cat > "${WRAPPER}" <<'WRAPPER_EOF'
#!/bin/bash
# Auto-generated by setup-browsermcp-tunnel.sh — re-run that script to update.
# Resolves the S5 terminal container IP over SSH, then opens the BrowserMCP
# tunnel. Restarted by systemd on drops, so terminal recreates (new IP) heal.
set -euo pipefail
S5="${S5_SSH_TARGET:-ari@100.85.113.67}"
TIP=$(ssh -o BatchMode=yes "$S5" "docker inspect remote-terminal-1 --format '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}'")
exec ssh -N -o ServerAliveInterval=30 -o ServerAliveCountMax=3 -o ExitOnForwardFailure=yes -o BatchMode=yes -L 9010:"$TIP":19010 "$S5"
WRAPPER_EOF
chmod +x "${WRAPPER}"
echo "Wrote ${WRAPPER}"

cat > "${UNIT}" <<'UNIT_EOF'
[Unit]
Description=BrowserMCP tunnel to S5 (extension pairing relay)
After=network-online.target
Wants=network-online.target

[Service]
ExecStart=%h/.local/bin/browsermcp-tunnel.sh
Restart=always
RestartSec=10

[Install]
WantedBy=default.target
UNIT_EOF
echo "Wrote ${UNIT}"

if [ "${OFFLINE}" = 1 ]; then
  echo "OFFLINE=1: skipping SSH check, systemd enablement, and verification."
  exit 0
fi

command -v ssh >/dev/null 2>&1 || { echo "error: ssh not found in PATH" >&2; exit 1; }
command -v systemctl >/dev/null 2>&1 || { echo "error: systemctl not found (systemd user services required)" >&2; exit 1; }

echo "==> Checking SSH key auth to ${S5_SSH_TARGET}..."
if ! ssh -o BatchMode=yes -o ConnectTimeout=15 "${S5_SSH_TARGET}" true; then
  echo "error: passwordless SSH to ${S5_SSH_TARGET} failed." >&2
  echo "Run once: ssh-copy-id ${S5_SSH_TARGET} (and join the tailnet), then re-run this script." >&2
  exit 1
fi

echo "==> Enabling browsermcp-tunnel.service..."
systemctl --user daemon-reload
systemctl --user enable --now browsermcp-tunnel.service

if command -v curl >/dev/null 2>&1; then
  echo "==> Verifying the tunnel (up to ~30s)..."
  ok=0
  for _ in 1 2 3 4 5 6; do
    if curl -sf -m 5 http://localhost:9010/browsermcp/status >/dev/null 2>&1; then ok=1; break; fi
    sleep 5
  done
  if [ "${ok}" = 1 ]; then
    echo "Tunnel verified:"
    curl -s -m 5 http://localhost:9010/browsermcp/status
    echo
  else
    echo "warning: daemon did not answer yet (is Tailscale up on this laptop?)." >&2
    echo "The service self-heals (Restart=always); check: systemctl --user status browsermcp-tunnel.service" >&2
  fi
else
  echo "note: curl not installed; skipping live check."
  echo "Verify manually: curl http://localhost:9010/browsermcp/status"
fi

echo "Tip: 'sudo loginctl enable-linger \$USER' keeps it running without an active login."
echo "==> Done."
