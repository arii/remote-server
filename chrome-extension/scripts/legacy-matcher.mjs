// Pure transform: extension/lib/matcher.js (ES module) -> the classic-script
// twin the content script consumes. content-script.js cannot import ES
// modules, so scripts/build.mjs emits matcher.legacy.js from this one source
// and the functions reach the content script through the existing
// window.__LOCALFORM_*__ hook pattern (OD-19 D2; no bundler).
//
// The transform is intentionally dumb and deterministic: strip `export `
// prefixes and append the window attach. A committed-file freshness test
// (tests/matcher.test.js) fails if matcher.legacy.js drifts from this
// transform of matcher.js.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const LIB_DIR = path.resolve(__dirname, '../extension/lib');

export const LEGACY_HOOK = "__LOCALFORM_MATCHER__";

// Function names the legacy attach exposes; update together with matcher.js.
export const LEGACY_EXPORTS = [
  "escapeRegExp",
  "normalizeLabel",
  "aliasMatches",
  "cleanLabelText",
  "resolveLabel"
];

export function toClassicMatcher(src) {
  const classic = src.replace(/^export\s+/gm, "");
  if (/^\s*(import|export)\b/m.test(classic)) {
    throw new Error(
      "lib/matcher.js contains module syntax the legacy transform cannot strip (bare import/export)"
    );
  }
  const attach =
    `\n// ─── Generated attach — edit lib/matcher.js, not this file. ───\n` +
    `if (typeof window !== "undefined") {\n` +
    `  window.${LEGACY_HOOK} = { ${LEGACY_EXPORTS.join(", ")} };\n` +
    `}\n`;
  return (
    `// GENERATED by scripts/build.mjs from lib/matcher.js — do not edit.\n` +
    classic.trimEnd() +
    "\n" +
    attach
  );
}

// Emitter used by build.mjs: regenerate extension/lib/matcher.legacy.js from
// lib/matcher.js and return the written path.
export function emitLegacyMatcher() {
  const outPath = path.join(LIB_DIR, 'matcher.legacy.js');
  fs.writeFileSync(outPath, toClassicMatcher(fs.readFileSync(path.join(LIB_DIR, 'matcher.js'), 'utf8')));
  return outPath;
}
